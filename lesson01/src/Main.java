public class Main {
    public static void main(String[] args) {
        // VETORES (PARTE 01) - AULA 01
        int[] vetor = new int[10];

        // Adicionando elementos no vetor.
        vetor[0] = 3;
        vetor[1] = 4;
        vetor[2] = 8;
        vetor[3] = 13;
        vetor[4] = 15;
        vetor[5] = 51;
        vetor[6] = 33;

        // Imprimindo vetor.
        for (int i = 0; i < vetor.length; i++) {
            System.out.println(vetor[i]);
        }

        // vetor.length: mostra o tamanho de um vetor.

    }
}